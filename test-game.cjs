const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.existsSync(__dirname + '/Mumbai-Toot.html') ? fs.readFileSync(__dirname + '/Mumbai-Toot.html', 'utf8') : '';
assert.ok(fs.existsSync(__dirname + '/index.html'), 'Hosting entry point index.html must exist');
assert.equal(fs.readFileSync(__dirname + '/index.html', 'utf8'), html, 'Hosted entry point must match the standalone game');
const source = html.match(/<script id="engine">([\s\S]*?)<\/script>/);
assert.ok(source, 'Game must provide its playable engine');
const scope = {Math}; vm.createContext(scope); vm.runInContext(source[1], scope);
const E = scope.MumbaiEngine;
let s = E.create();
assert.equal(s.mode, 'ready');
E.start(s); assert.equal(s.mode, 'playing');
assert.equal(E.jump(s), true, 'grounded player can jump');
assert.ok(s.vy < 0, 'jump launches player upward');
assert.equal(E.jump(s), false, 'cannot jump repeatedly in mid-air');
E.step(s, 0.1, () => 0.5);
assert.ok(s.y < E.GROUND, 'player rises above the platform');
console.log('PASS: start, jump, airborne movement, no infinite jumps');
s = E.create(); E.start(s);
for(let i=0;i<100;i++) E.step(s, 1/120, () => 0.5);
assert.ok(s.trains.length > 0, 'incoming trains spawn');
s.trains=[{x:180,w:130,h:82,passed:false}]; E.step(s, 1/120);
assert.equal(s.mode, 'over', 'grounded collision ends the run');
E.start(s); s.y=260; s.vy=0; s.trains=[{x:180,w:130,h:82,passed:false}]; E.step(s,1/120);
assert.equal(s.mode,'playing','jumping clears train roof');
s.trains=[{x:0,w:120,h:82,passed:false}]; E.step(s,1/120);
assert.equal(s.cleared,1,'passing a train scores once'); E.step(s,1/120); assert.equal(s.cleared,1);
E.pause(s); const before=JSON.stringify(s); E.step(s,0.1); assert.equal(JSON.stringify(s),before,'pause freezes simulation');
E.pause(s); assert.equal(s.mode,'playing');
E.start(s); assert.equal(s.cleared,0); assert.equal(s.trains.length,0); assert.equal(s.y,E.GROUND);
E.jump(s); for(let i=0;i<120;i++) E.step(s,1/120,()=>0.5); assert.equal(s.y,E.GROUND,'land exactly on ground');
assert.equal(E.jump(s),true,'can jump after landing');
E.start(s); for(let i=0;i<36000;i++){ s.trains=[]; E.step(s,1/120,()=>0.5); } assert.ok(s.speed<=580,'difficulty speed is capped');
console.log('PASS: spawning, collision, clearance, scoring, pause, restart, landing, speed cap');
